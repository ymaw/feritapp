const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const script = fs.readFileSync(path.join(root, 'script.js'), 'utf8');
const css = fs.readFileSync(path.join(root, 'css/notes.css'), 'utf8');
const migration = fs.readFileSync(path.join(root, 'supabase/migrations/20261114010000_create_notes.sql'), 'utf8');

assert.match(html, /id="viewNotes"/);
assert.match(html, /id="noteContent"[^>]*required/);
assert.match(html, /id="noteClient"/);
assert.match(html, /id="noteReminderEnabled"[^>]*type="checkbox"/);
assert.match(html, /id="noteReminderDate"[^>]*type="date"/);
assert.match(html, /id="noteReminderTime"[^>]*type="time"/);
assert.match(html, /data-view="notes"/);
assert.match(script, /async function loadNotes\(\)/);
assert.match(script, /sb\.from\('notes'\)\.select/);
assert.match(script, /sb\.from\('notes'\)\.insert/);
assert.match(script, /sb\.from\('notes'\)\.update/);
assert.match(script, /sb\.from\('notes'\)\.delete/);
assert.match(script, /client_id:clientId/);
assert.match(script, /reminder_at:reminderAt/);
assert.match(script, /if\(view === 'notes'\)\{ loadNotes\(\); \}/);
assert.match(css, /\.notes-editor\[hidden\]\s*\{\s*display:none/);
const notesTypeButtonBase = css.match(/\.notes-type-field>\.notes-label-create-btn\s*\{([^}]*)\}/);
assert.ok(notesTypeButtonBase, 'The type label creation button base rule must remain present');
assert.match(notesTypeButtonBase[1], /display:inline-flex/);
assert.match(notesTypeButtonBase[1], /align-items:center/);
assert.doesNotMatch(notesTypeButtonBase[1], /margin-top|padding|font-size/, 'The base rule must not repeat values supplied by the later compact alignment rule');
assert.match(css, /\.notes-type-field>\.notes-label-create-btn\s*\{\s*margin-top:0;padding:2px 0;font-size:11px;\s*\}/, 'The final compact alignment values must remain unchanged');
assert.match(migration, /enable row level security/i);
assert.match(migration, /create policy "Users can read their own notes"/i);
assert.match(migration, /create policy "Users can create their own notes"/i);
assert.match(migration, /create policy "Users can update their own notes"/i);
assert.match(migration, /create policy "Users can delete their own notes"/i);
assert.match(migration, /revoke all on public\.notes from anon/i);
assert.match(migration, /grant select, insert, update, delete on public\.notes to authenticated/i);
assert.match(migration, /client_id uuid null references public\.clients\(id\) on delete set null/i);
console.log('OK notes: CRUD UI, optional client and reminder fields, user-scoped RLS and authenticated-only grants.');
