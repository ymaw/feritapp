const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const script = fs.readFileSync(path.join(root, 'script.js'), 'utf8');
const migration = fs.readFileSync(path.join(root, 'supabase/migrations/20261114011000_add_navigation_preferences.sql'), 'utf8');
const nav = html.match(/<nav aria-label="Navegación principal" class="bottom-nav"[^>]*>[\s\S]*?<\/nav>/)?.[0] || '';
assert.equal((nav.match(/class="nav-item"/g) || []).length, 4, 'Mobile navigation must expose exactly four configurable slots');
assert.ok(nav.indexOf('data-nav-slot="2"') < nav.indexOf('id="openSheet"') && nav.indexOf('id="openSheet"') < nav.indexOf('data-nav-slot="3"'), 'The central create action must remain between the two pairs of slots');
assert.match(html, /id="settingsPanelPersonalization"/);
for (let i=1;i<=4;i++) assert.match(html,new RegExp('id="navigationSlot'+i+'"'));
assert.match(html,/id="saveNavigationBtn"/);
assert.match(script,/const DEFAULT_NAVIGATION_SLOTS = \['dashboard','sales','deliveries','notes'\]/);
assert.match(script,/async function saveNavigationSlots\(\)/);
assert.match(script,/navigation_slots:selected/);
assert.match(script,/function renderMoreMenu\(\)/);
assert.match(script,/new Set\(navigationSlots\)/);
assert.match(script,/if\(key === 'personalization'\) fillNavigationSelectors\(\)/);
assert.match(migration,/add column if not exists navigation_slots jsonb not null/i);
assert.match(migration,/jsonb_array_length\(navigation_slots\) = 4/i);
assert.ok(!/select\s+count\(distinct/i.test(migration),'Migration must not use subqueries in CHECK constraints');
console.log('OK navigation personalization: four slots, fixed central create action, account persistence and dynamic More menu.');
