const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const script = fs.readFileSync(path.join(root, 'script.js'), 'utf8');
const style = fs.readFileSync(path.join(root, 'css/style.css'), 'utf8');
const nav = html.match(/<nav aria-label="Navegación principal" class="bottom-nav"[\s\S]*?<\/nav>/)?.[0] || '';
const header = html.match(/<header>[\s\S]*?<\/header>/)?.[0] || '';
assert.ok(header.includes('id="headerMoreBtn"'), 'More action must live in the app header');
assert.ok(header.includes('aria-label="Abrir menú Más"'), 'Header action must have an accessible name');
assert.ok(header.includes('class="header-more-icon">⋮'), 'Header action must use the vertical overflow icon');
assert.ok(!nav.includes('id="moreBtn"'), 'More must not occupy a bottom navigation slot');
assert.ok(nav.includes('id="openSheet"'), 'Central create action must remain in the bottom navigation');
assert.ok(script.includes("const headerMoreBtn = document.getElementById('headerMoreBtn')"), 'Menu controller must use the header trigger');
assert.ok(script.includes('toggleMenuFrom(headerMoreBtn)'), 'Dropdown must be anchored to the header trigger');
assert.match(style, /\.header-more-btn\s*\{[\s\S]*?position:\s*absolute/);
assert.match(style, /@media\(min-width:900px\)\{\.header-more-btn\{display:none!important;\}\}/);
assert.match(style, /@media\(max-width:899px\)\{\.header-more-btn\{display:inline-flex;\}/);
console.log('OK mobile navigation: More moved to header, central create action preserved, desktop sidebar unaffected.');
